LN2 = math.log(2.0)


def boot_ci(values: list[float], seed: int, B: int = 1000) -> tuple[float, float]:
    """Percentile bootstrap CI of the mean over items (documents, probes, pairs)."""
    if not values:
        return (float("nan"), float("nan"))
    rng = np.random.default_rng(seed); arr = np.array(values, dtype=float)
    means = arr[rng.integers(0, len(arr), (B, len(arr)))].mean(axis=1)
    return (float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5)))


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n; den = 1 + z * z / n; c = (p + z * z / (2 * n)) / den; h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (c - h, c + h)


# ---------------- model-based metrics (batched scorer) ----------------
class Scorer:
    """Batched negative log-likelihood scorer. Batches are sized by tokens so that the full-vocabulary logits
    (262k entries for gemma-3) stay within memory: ~4,096 tokens per forward pass."""

    def __init__(self, checkpoint: str, dtype: str = "bfloat16", batch_tokens: int = 4096):
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer
        self.torch = torch
        self.tok = AutoTokenizer.from_pretrained(checkpoint)
        if self.tok.pad_token is None:
            self.tok.pad_token = self.tok.eos_token
        self.tok.padding_side = "right"
        self.model = AutoModelForCausalLM.from_pretrained(checkpoint, dtype=getattr(torch, dtype), device_map="auto").eval()   # `dtype`: transformers >= 4.56
        self.batch_tokens = batch_tokens
        self.logprob_chunk = 1024        # positions per fp32 log-softmax call (memory only; results identical)

    def nll_batch(self, texts: list[str], max_len: int = 1024) -> list[tuple[float, int]]:
        """Returns (total NLL in nats over predicted tokens, number of predicted tokens) per text. Predicted tokens are all
        tokens after the first one (the BOS token added by the tokenizer is the first token)."""
        torch = self.torch
        out: list[tuple[float, int]] = [None] * len(texts)  # type: ignore
        if not texts:
            return out
        # token lengths up front; a batch grows while (texts in batch) x (longest of them) stays within batch_tokens, because
        # padding goes to the LONGEST text. The old rule sized the batch from its shortest text and, with a few short texts
        # in front of long ones, built a 14k-token batch (14 GiB of logits; smoke test 2026-10-13). Same per-text arithmetic.
        lens = [min(max_len, max(1, len(ids))) for ids in self.tok(texts, truncation=True, max_length=max_len)["input_ids"]]
        order = sorted(range(len(texts)), key=lambda k: lens[k])
        i = 0
        while i < len(order):
            j = i + 1
            while j < len(order) and (j + 1 - i) * lens[order[j]] <= self.batch_tokens:
                j += 1
            idx = order[i:j]; i = j
            enc = self.tok([texts[k] for k in idx], return_tensors="pt", padding=True, truncation=True, max_length=max_len).to(self.model.device)
            with torch.no_grad():
                logits = self.model(**enc).logits
                labels = enc["input_ids"][:, 1:]; mask = enc["attention_mask"][:, 1:].float()
                # fp32 log-softmax in chunks of positions: the same row-wise arithmetic as one call, but peak memory ~4 GB
                # instead of ~11 GB for a 4,096-token batch with the 262k vocabulary (the scorer held 21 GB and survived
                # only on allocator retries, gen-0 run 2026-10-13)
                lp = torch.empty(labels.shape, dtype=torch.float32, device=logits.device)
                T = labels.shape[1]; chunk = self.logprob_chunk
                for b in range(labels.shape[0]):
                    for c0 in range(0, T, chunk):
                        c1 = min(T, c0 + chunk)
                        lp[b, c0:c1] = torch.log_softmax(logits[b, c0:c1, :].float(), dim=-1).gather(-1, labels[b, c0:c1].unsqueeze(-1)).squeeze(-1)
            nll = -(lp * mask).sum(1); n = mask.sum(1)
            for k, a, b in zip(idx, nll.tolist(), n.tolist()):
                out[k] = (float(a), int(b))
            del logits, lp
        return out

    def nll(self, text: str, max_len: int = 1024) -> tuple[float, int]:
        return self.nll_batch([text], max_len)[0]


def heldout_perplexity(scorer: Scorer, language: str, n_docs: int, seed: int, sidecar_dir: Path | None) -> dict:
    """Regular held-out docs (first n_docs without the fresh flag) and the fresh slice (all docs flagged fresh) are scored
    separately (reviewer fix: the fresh slice used to be cut off by the n_docs slice). Reports document-macro log-ppl
    (mean of per-document mean NLL, pre-registered primary), token-micro log-ppl, and bits per byte (tokenizer-independent)."""
    allh = list(read_jsonl(HELDOUT / f"{language}_heldout.jsonl"))
    regular = [d for d in allh if not d.get("fresh")][:n_docs]
    fresh = [d for d in allh if d.get("fresh")]
    out, rows = {}, []
    for tag, docs in (("heldout", regular), ("fresh", fresh)):
        if not docs:
            continue
        res = scorer.nll_batch([d["text"] for d in docs])
        per_doc, tot_nll, tot_tok, tot_bytes, tot_chars = [], 0.0, 0, 0, 0
        for d, (nll, n) in zip(docs, res):
            if n <= 0:
                continue
            nb = len(d["text"].encode("utf-8")); nc = len(d["text"])
            per_doc.append(nll / n); tot_nll += nll; tot_tok += n; tot_bytes += nb; tot_chars += nc
            rows.append({"doc_id": d["doc_id"], "set": tag, "nll_total": nll, "n_tokens": n, "n_bytes": nb, "n_chars": nc, "n_words": len(words(d["text"]))})
        lo, hi = boot_ci(per_doc, seed)
        out[f"log_ppl_{tag}"] = (float(np.mean(per_doc)), lo, hi, len(per_doc))
        out[f"log_ppl_micro_{tag}"] = (tot_nll / max(1, tot_tok), float("nan"), float("nan"), tot_tok)
        # bits per byte / per character with a bootstrap over documents of the ratio of sums
        rng = np.random.default_rng(seed); nl = np.array([r["nll_total"] for r in rows if r["set"] == tag]); by = np.array([r["n_bytes"] for r in rows if r["set"] == tag]); ch = np.array([r["n_chars"] for r in rows if r["set"] == tag])
        bpb = float(nl.sum() / by.sum() / LN2); bpc = float(nl.sum() / ch.sum() / LN2)
        if len(nl) > 1:
            ids = rng.integers(0, len(nl), (1000, len(nl))); bb = (nl[ids].sum(1) / by[ids].sum(1) / LN2); cc = (nl[ids].sum(1) / ch[ids].sum(1) / LN2)
            out[f"bpb_{tag}"] = (bpb, float(np.percentile(bb, 2.5)), float(np.percentile(bb, 97.5)), len(nl))
            out[f"bpc_{tag}"] = (bpc, float(np.percentile(cc, 2.5)), float(np.percentile(cc, 97.5)), len(nl))
        else:
            out[f"bpb_{tag}"] = (bpb, float("nan"), float("nan"), len(nl)); out[f"bpc_{tag}"] = (bpc, float("nan"), float("nan"), len(nl))
    if sidecar_dir is not None:
        write_jsonl(sidecar_dir / "heldout_nll.jsonl", rows)
    return out


def tail_fact_recall(scorer: Scorer, language: str, seed: int, sidecar_dir: Path | None) -> dict:
    """Cloze probes scored two ways from the same forward passes: (A, pre-registered) total sentence log-likelihood, gold
    must rank first among gold + 3 distractors; (B, robustness) object-conditional log-likelihood per object token
    (sentence NLL minus NLL of the frame before {O}, divided by the number of object-slot tokens). Per-candidate scores
    are written to probe_scores.jsonl so that other scoring rules can be applied later without the GPU."""
    probes = [p for p in read_jsonl(PROBES / f"{language}_tail_facts.jsonl") if p.get("verification") != "rejected"]
    if not probes:
        return {}
    sents, frames = [], []
    for p in probes:
        frame_prefix = p["template"].split("{O}")[0].format(S=p["subject"])
        frames.append(frame_prefix)
        for cand in [p["gold"]] + p["distractors"]:
            sents.append(p["template"].format(S=p["subject"], O=cand))
    rs = scorer.nll_batch(sents, max_len=128); rf = scorer.nll_batch(frames, max_len=128)
    hits = {"A": {"ALL": [], "HEAD": [], "MID": [], "TAIL": []}, "B": {"ALL": [], "HEAD": [], "MID": [], "TAIL": []}}
    rows = []
    for k, p in enumerate(probes):
        cands = [p["gold"]] + p["distractors"]
        fr_nll, fr_n = rf[k]
        scoresA, scoresB = [], []
        for c_i, cand in enumerate(cands):
            nll, n = rs[4 * k + c_i]
            obj_nll = nll - fr_nll; obj_n = max(1, n - fr_n)
            scoresA.append(-nll); scoresB.append(-obj_nll / obj_n)
            rows.append({"probe_id": p["probe_id"], "stratum": p["stratum"], "relation": p["relation"], "candidate": cand, "is_gold": c_i == 0,
                         "nll_total": nll, "n_tokens": n, "frame_nll": fr_nll, "frame_tokens": fr_n, "object_nll": obj_nll, "object_tokens": obj_n})
        for rule, sc in (("A", scoresA), ("B", scoresB)):
            hit = 1.0 if sc[0] > max(sc[1:]) else 0.0
            hits[rule]["ALL"].append(hit); hits[rule][p["stratum"]].append(hit)
    if sidecar_dir is not None:
        write_jsonl(sidecar_dir / "probe_scores.jsonl", rows)
    out = {}
    for rule, d in hits.items():
        for strat, v in d.items():
            if v:
                lo, hi = wilson(int(sum(v)), len(v))
                name = f"tail_fact_recall_{strat}" if rule == "A" else f"tail_fact_recall_norm_{strat}"
                out[name] = (float(np.mean(v)), lo, hi, len(v))
    return out


def bias_preference(scorer: Scorer, language: str, seed: int, sidecar_dir: Path | None) -> dict:
    pairs = list(read_jsonl(PROBES / f"{language}_bias.jsonl"))
    if not pairs:
        return {}
    res = scorer.nll_batch([p["stereo"] for p in pairs] + [p["anti"] for p in pairs], max_len=256)
    n = len(pairs); pref, rows = [], []
    for i, p in enumerate(pairs):
        s_nll, s_n = res[i]; a_nll, a_n = res[n + i]
        pref.append(1.0 if -s_nll > -a_nll else 0.0)
        rows.append({"pair_id": p["pair_id"], "stereo_nll": s_nll, "stereo_tokens": s_n, "anti_nll": a_nll, "anti_tokens": a_n})
    if sidecar_dir is not None:
        write_jsonl(sidecar_dir / "bias_scores.jsonl", rows)
    lo, hi = wilson(int(sum(pref)), len(pref))
    return {"stereotype_preference": (float(np.mean(pref)), lo, hi, len(pref))}


# ---------------- sample-based lexical metrics (no GPU) ----------------
def _window_stats(toks_per_doc: list[list[str]], order: list[int], window: int, rare: set | None, thr: float = 0.72) -> dict:
    """Metrics on the first `window` word tokens of the documents taken in `order` (pre-specified start = 0)."""
    win: list[str] = []
    for i in order:
        win.extend(toks_per_doc[i])
        if len(win) >= window:
            break
    win = win[:window]
    out = {}
    for n in (1, 2, 3, 4):
        grams = [tuple(win[i:i + n]) for i in range(max(0, len(win) - n + 1))]
        out[f"distinct_{n}"] = len(set(grams)) / max(1, len(grams))
    out["ttr_window"] = len(set(win)) / max(1, len(win))
    factors, types, count = 0, set(), 0
    for w in win:
        types.add(w); count += 1
        if len(types) / count <= thr:
            factors += 1; types, count = set(), 0
    if count:
        factors += (1 - len(types) / count) / (1 - thr)
    out["mtld"] = len(win) / factors if factors else float("nan")
    for n in (1, 2):
        c = Counter(tuple(win[i:i + n]) for i in range(max(0, len(win) - n + 1))); tot = sum(c.values())
        out[f"entropy_{n}gram"] = -sum(v / tot * math.log2(v / tot) for v in c.values()) if tot else float("nan")
    if rare is not None:
        out["tail_mass"] = float(np.mean([1.0 if w in rare else 0.0 for w in win])) if win else float("nan")
    # character 5-gram distinctness on the same window (robustness for inflection-driven type inflation)
    text = " ".join(win)
    c5 = [text[i:i + 5] for i in range(max(0, len(text) - 4))]
    out["distinct_char5"] = len(set(c5)) / max(1, len(c5))
    out["window_tokens"] = len(win)
    return out


def lexical_metrics(sample_docs: list[dict], language: str, cfg: dict, seed: int, seed_vocab: Counter | None, tokenizer=None) -> dict:
    """Lexical metrics on the generated continuation of each sample document ("text" field; the real prefix is in "prefix"
    and excluded). All word tokens are lower-cased on both sides (reviewer fix: the seed vocabulary was lower-cased but the
    sample was not). Window metrics get a bootstrap CI by resampling documents (B = metrics.bootstrap_resamples)."""
    m = cfg["metrics"]; rnd = random.Random(seed)
    docs = [d["text"] for d in sample_docs]
    toks_per_doc = [[w.lower() for w in words(t)] for t in docs]
    order = list(range(len(docs))); rnd.shuffle(order)
    window = m["ttr_window_tokens"]
    rare = None
    if seed_vocab:
        # rarest 10% of seed types among types with >= 2 occurrences; deterministic tie-break by (count, type)
        n_types = len(seed_vocab); rare_cut = max(1, int(n_types * m["tail_rare_fraction"]))
        rare = {w for w, _ in sorted(seed_vocab.items(), key=lambda kv: (kv[1], kv[0]))[:rare_cut]}
    point = _window_stats(toks_per_doc, order, window, rare)
    B = int(m.get("bootstrap_resamples", 300))
    rng = np.random.default_rng(seed)
    boots: dict[str, list[float]] = {k: [] for k in point}
    # CI by repeated document SUBSAMPLING (random permutations without replacement): the window uses only part of the
    # 2,000 documents, so each permutation fills it with a different set of distinct documents. A with-replacement
    # bootstrap would duplicate documents and bias distinct-n downward (verified in the offline test), so it is not used.
    for _ in range(B):
        bo = [order[i] for i in rng.permutation(len(order))]
        st = _window_stats(toks_per_doc, bo, window, rare)
        for k, v in st.items():
            boots[k].append(v)
    out = {}
    for k, v in point.items():
        if k == "window_tokens":
            out[k] = (float(v), float("nan"), float("nan"), len(docs)); continue
        arr = np.array(boots[k], dtype=float)
        out[k] = (float(v), float(np.nanpercentile(arr, 2.5)), float(np.nanpercentile(arr, 97.5)), int(point["window_tokens"]))
    sr = [script_ratio(t, language) for t in docs]
    lo, hi = boot_ci(sr, seed); out["script_ratio_mean"] = (float(np.mean(sr)), lo, hi, len(sr))
    out["script_docs_ge95"] = (float(np.mean([1.0 if s >= 0.95 else 0.0 for s in sr])), *wilson(sum(1 for s in sr if s >= 0.95), len(sr)), len(sr))
    rep = [repeat_4gram_rate(ws) for ws in toks_per_doc]
    lo, hi = boot_ci(rep, seed); out["repeat_4gram_rate"] = (float(np.mean(rep)), lo, hi, len(rep))
    out["degenerate_docs"] = (float(np.mean([1.0 if r >= 0.5 else 0.0 for r in rep])), *wilson(sum(1 for r in rep if r >= 0.5), len(rep)), len(rep))
    lens_tok = [d.get("n_tokens") if d.get("n_tokens") is not None else len(ws) for d, ws in zip(sample_docs, toks_per_doc)]
    lens_w = [len(ws) for ws in toks_per_doc]; lens_c = [len(t) for t in docs]; lens_b = [len(t.encode("utf-8")) for t in docs]
    for name, xs in (("mean_length_tokens", lens_tok), ("mean_length_words", lens_w), ("mean_length_chars", lens_c), ("mean_length_bytes", lens_b)):
        lo, hi = boot_ci(xs, seed); out[name] = (float(np.mean(xs)), lo, hi, len(xs))
    out["median_length_tokens"] = (float(np.median(lens_tok)), float("nan"), float("nan"), len(lens_tok))
    out["cap_hit_rate"] = (float(np.mean([1.0 if d.get("hit_cap") else 0.0 for d in sample_docs])), *wilson(sum(1 for d in sample_docs if d.get("hit_cap")), len(sample_docs)), len(sample_docs))
    out["empty_docs"] = (float(np.mean([1.0 if len(ws) == 0 else 0.0 for ws in toks_per_doc])), float("nan"), float("nan"), len(docs))
    if tokenizer is not None:
        tpw = [len(tokenizer(t, add_special_tokens=False)["input_ids"]) / max(1, len(ws)) for t, ws in zip(docs, toks_per_doc) if ws]
        lo, hi = boot_ci(tpw, seed); out["fertility_tokens_per_word"] = (float(np.mean(tpw)) if tpw else float("nan"), lo, hi, len(tpw))
    return out


def seed_vocab_for(language: str) -> Counter:
    c = Counter()
    for d in read_jsonl(CORPORA / f"{language}_seed.jsonl"):
        c.update(w.lower() for w in words(d["text"]))
    return Counter({w: n for w, n in c.items() if n >= 2})


def sample_under_reference(ref: Scorer, sample_docs: list[dict], max_len: int, seed: int, sidecar_dir: Path | None) -> dict:
    """Per-document NLL of the generated sample (prefix + continuation) under a fixed reference model (the language's
    gen-0 model): the distribution of generated-text perplexity under a fixed scorer is the classic collapse signature
    (tails vanish, mass concentrates). Written to sample_scores.jsonl; summary metrics returned."""
    texts = [(d.get("prefix") or "") + d["text"] for d in sample_docs]
    res = ref.nll_batch(texts, max_len=max_len)
    rows, per_tok = [], []
    for d, (nll, n) in zip(sample_docs, res):
        rows.append({"doc_id": d["doc_id"], "nll_total_ref": nll, "n_tokens": n})
        if n > 0:
            per_tok.append(nll / n)
    if sidecar_dir is not None:
        write_jsonl(sidecar_dir / "sample_scores.jsonl", rows)
    if not per_tok:
        return {}
    lo, hi = boot_ci(per_tok, seed)
    arr = np.array(per_tok)
    return {"sample_nll_ref_mean": (float(arr.mean()), lo, hi, len(per_tok)), "sample_nll_ref_sd": (float(arr.std()), float("nan"), float("nan"), len(per_tok)),
            "sample_nll_ref_p5": (float(np.percentile(arr, 5)), float("nan"), float("nan"), len(per_tok)), "sample_nll_ref_p95": (float(np.percentile(arr, 95)), float("nan"), float("nan"), len(per_tok))}


def compute_all(chain: str, generation: int, checkpoint: str, language: str, sample_docs: list[dict], cfg: dict, use_gpu: bool = True,
                sidecar_dir: Path | None = None, reference_checkpoint: str | None = None) -> list[dict]:
    seed = cfg["seed"] + generation
    recs = {}
    tokenizer = None
    if use_gpu:
        scorer = Scorer(checkpoint, cfg["training"]["dtype"])
        tokenizer = scorer.tok
        recs.update(heldout_perplexity(scorer, language, cfg["metrics"]["heldout_docs"], seed, sidecar_dir))
        recs.update(tail_fact_recall(scorer, language, seed, sidecar_dir))
        recs.update(bias_preference(scorer, language, seed, sidecar_dir))
        del scorer
        import gc
        import torch
        gc.collect(); torch.cuda.empty_cache()                  # free the GPU before the reference scorer / the next stage
        if reference_checkpoint:
            ref = Scorer(reference_checkpoint, cfg["training"]["dtype"])
            max_len = max((len(d.get("prefix_ids") or []) + int(d.get("n_tokens") or 0)) for d in sample_docs) + 8 if sample_docs else 1024
            recs.update(sample_under_reference(ref, sample_docs, min(1024, max_len), seed, sidecar_dir))
            del ref
        try:
            import torch; torch.cuda.empty_cache()
        except Exception:
            pass
    recs.update(lexical_metrics(sample_docs, language, cfg, seed, seed_vocab_for(language), tokenizer))
    out = [{"chain_id": chain, "generation": generation, "language": language, "metric": k, "value": float(v[0]), "ci_lo": float(v[1]), "ci_hi": float(v[2]), "n": int(v[3]),
            "checkpoint": checkpoint, "computed_at": now_iso()} for k, v in recs.items()]
    append_jsonl(RESULTS / "metrics.jsonl", out)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--chain", required=True); ap.add_argument("--generation", type=int, required=True); ap.add_argument("--checkpoint", required=True)
    ap.add_argument("--no-gpu", action="store_true"); ap.add_argument("--reference", help="gen-0 checkpoint for sample_scores.jsonl")
    a = ap.parse_args()
    cfg = load_chains_cfg()
    language = a.chain.split("-")[0]
    gdir = CHAINS / a.chain / (f"gen_{a.generation}" if a.generation >= 0 else "base")
    sample_docs = list(read_jsonl(gdir / "sample.jsonl"))
    recs = compute_all(a.chain, a.generation, a.checkpoint, language, sample_docs, cfg, use_gpu=not a.no_gpu, sidecar_dir=gdir, reference_checkpoint=a.reference)
    for r in recs:
        print(f"{r['metric']:28s} {r['value']:.4f}  n={r['n']}")


if __name__ == "__main__":
    main()
